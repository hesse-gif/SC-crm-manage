import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { persistImportRows, transformFluDocToMixmax, rowForExistingMessage } from './mixmax-import-flu.mjs';
import { buildMessageReconcilePlan, canonicalMessageTargetId, legacyShortMessageTargetId, applyPlan } from './mixmax-reconcile-messages.mjs';
const require = createRequire(new URL('../functions/package.json', import.meta.url));
assert.equal(process.env.GCLOUD_PROJECT, 'demo-mixmax');
assert.match(process.env.FIRESTORE_EMULATOR_HOST ?? '', /^(127\.0\.0\.1|localhost):8480$/);
const { initializeApp, deleteApp } = require('firebase-admin/app');
const { getFirestore } = require('firebase-admin/firestore');
const app = initializeApp({ projectId: 'demo-mixmax' }, 'import-verification');
const db = getFirestore(app, 'mixmax');
try {
  const row = transformFluDocToMixmax({ collection: 'message_sources', id: `race-${Date.now()}`, data: { conversationId: 'first', text: 'original' } });
  const counts = Array.from({length: 6}, () => ({created: 0, skipped: 0}));
  await Promise.all(counts.map(count => persistImportRows(db, [row], true, count)));
  assert.equal(counts.reduce((n, count) => n + count.created, 0), 1);
  assert.equal(counts.reduce((n, count) => n + count.skipped, 0), 5);
  const ref = db.doc(`${row.targetCollection}/${row.targetId}`);
  await ref.update({text: 'native edit'});
  await persistImportRows(db, [row], true, {created: 0, skipped: 0});
  assert.equal((await ref.get()).data().text, 'native edit');
  const second = {...row, data: {...row.data, threadId: 'second'}};
  const alias = rowForExistingMessage(row.data, second);
  await persistImportRows(db, [second], true, {created: 0, skipped: 0});
  assert.equal((await db.doc(`${alias.targetCollection}/${alias.targetId}`).get()).data().threadId, 'second');
  assert.equal((await ref.get()).data().text, 'native edit');
  const sourceId = `repair-${Date.now()}`;
  const original = transformFluDocToMixmax({collection: 'message_sources', id: sourceId, data: {conversationId: 'repair-thread', body: 'full source body'}}).data;
  const shortRef = db.doc(`mixmax_messages/${legacyShortMessageTargetId(sourceId)}`);
  await shortRef.create({...original, text: 'legacy duplicate'});
  const plan = buildMessageReconcilePlan({sourceId, sourceData: {conversationId: 'repair-thread', body: 'full source body'}, legacyData: (await shortRef.get()).data()});
  await db.runTransaction(async tx => applyPlan(db, tx, plan));
  assert.equal((await shortRef.get()).exists, false);
  assert.equal((await db.doc(`mixmax_messages/${canonicalMessageTargetId(sourceId)}`).get()).data().text, 'full source body');
  const backup = plan.operations.find(op => op.type === 'backup-and-delete-legacy');
  assert.equal((await db.doc(`mixmax_import_backups/${backup.backupId}`).get()).data().data.text, 'legacy duplicate');
  console.log('PASS: concurrent import creates exactly once, preserves edits and each conversation association.');
  console.log('PASS: message reference repair retains full body and backs up duplicate atomically before removal.');
} finally { await deleteApp(app); }
